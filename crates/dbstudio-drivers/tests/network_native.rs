//! Offline native contract checks. External PostgreSQL/MySQL/TLS/SSH acceptance is scheduled by Lead.
use dbstudio_drivers::{network as n,tls,tunnel};
use dbstudio_protocol::{ConnectionConfig,SecretMap};
use serde_json::json;

fn config(dialect:&str,options:serde_json::Value)->ConnectionConfig{
    serde_json::from_value(json!({"dialectId":dialect,"name":"synthetic","options":options})).unwrap()
}
#[test]
fn raw_object_ids_escape_namespace_and_quote_identifiers(){
    let id=format!("table:{}.{}",n::escape_id("schema.name"),n::escape_id("odd\\table"));
    assert_eq!(n::table_id(&id).unwrap(),("schema.name".into(),"odd\\table".into()));
    assert_eq!(n::qualified(&id,false).unwrap(),"\"schema.name\".\"odd\\table\"");
    assert_eq!(n::quote("x`y",true),"`x``y`");
    assert!(n::table_id("table:public.a.b").is_err());
    assert!(n::table_id("connection:owner|table:public.a").is_err());
}
#[test]
fn pg_binding_is_positional_and_ignores_quotes_comments_dollar_strings(){
    let(sql,values)=n::bind_named("/* outer /* nested */ ok */ SELECT $2::text, $1, $2, '$9', $$ $8 ; $$ -- $7\n",&json!({"parameters":[{"name":"$1","value":7},{"name":"$2","value":"fixture"}]}),true).unwrap();
    assert_eq!(values,vec![json!(7),json!("fixture")]);
    assert!(sql.contains("$2::text"));
    assert!(n::bind_named("SELECT $2",&json!({"parameters":[{"name":"$2","value":1}]}),true).is_err());
    assert!(n::bind_named("SELECT $1",&json!({}),true).is_err());
    assert!(n::bind_named("SELECT $0",&json!({}),true).is_err());
}
#[test]
fn mysql_binding_preserves_literals_and_rejects_excess_or_missing_values(){
    let(sql,values)=n::bind_named("SELECT ?, '?', `?`, ? # trailing ?\n",&json!({"parameters":[{"name":"?1","value":true},{"name":"?2","value":null}]}),false).unwrap();
    assert_eq!(sql,"SELECT ?, '?', `?`, ?");assert_eq!(values,vec![json!(true),json!(null)]);
    assert!(n::bind_named("SELECT ?",&json!({}),false).is_err());
    assert!(n::bind_named("SELECT 1",&json!({"parameters":[{"name":"?1","value":1}]}),false).is_err());
    assert!(n::bind_named("SELECT :x",&json!({"parameters":[{"name":"x","value":1}]}),false).is_err());
    assert!(n::bind_named("SELECT 1 /*! ; DELETE FROM x */",&json!({}),false).is_err());
    assert_eq!(n::bind_named("SELECT 1--2 AS value",&json!({}),false).unwrap().0,"SELECT 1--2 AS value");
    assert_eq!(n::bind_named("SELECT 1-- comment\n",&json!({}),false).unwrap().0,"SELECT 1");
}
#[test]
fn multiple_statements_and_unterminated_constructs_are_rejected(){
    for sql in ["SELECT 1;DELETE FROM fixture","SELECT 'unterminated","SELECT 1 /* unfinished","SELECT $$unfinished"]{
        assert!(n::bind_named(sql,&json!({}),true).is_err(),"fixture SQL should fail");
    }
    assert!(n::bind_named("SELECT ';' ; -- terminal comment",&json!({}),true).is_ok());
}
#[test]
fn truncated_grid_values_cannot_be_written_back(){
    assert!(n::cell_param(&json!({"kind":"text","text":"preview","truncated":true})).is_err());
    assert!(n::cell_param(&json!({"kind":"blob","previewBase64":"YQ==","truncated":true})).is_err());
    assert_eq!(n::cell_param(&json!({"kind":"blob","previewBase64":"YQ==","truncated":false})).unwrap(),json!({"$binary":"YQ=="}));
    assert_eq!(n::text_cell("short",false),json!({"kind":"text","text":"short"}));
    assert_eq!(n::blob_cell(&[1;300],false)["truncated"],true);
}
#[test]
fn tls_modes_are_explicit_and_ssh_requires_pin_before_network(){
    let pg=config("postgresql",json!({}));assert!(matches!(tls::mode(&pg,true).unwrap(),tls::TlsMode::Prefer));
    let my=config("mysql",json!({}));assert!(matches!(tls::mode(&my,false).unwrap(),tls::TlsMode::Disable));
    assert!(tls::mode(&config("postgresql",json!({"sslmode":"allow"})),true).is_err());
    let ssh=config("postgresql",json!({"sshHost":"synthetic.invalid"}));
    let error=tunnel::open(&ssh,&SecretMap::new(),"db.fixture.invalid",5432).err().unwrap();
    assert_eq!(error.code,"ssh_host_key_required");assert!(!error.message.contains("synthetic.invalid"));
}
#[test]
fn native_ddl_quotes_names_and_rejects_type_default_injection(){
    let spec=json!({"name":"public.fixture","columns":[{"name":"id","typeName":"INTEGER","primaryKeyOrdinal":1,"autoIncrement":true},{"name":"name","typeName":"VARCHAR(64)","defaultValue":"'O''Brien'"}]});
    let sql=n::create_table_sql(&spec,false).unwrap();assert!(sql.contains("GENERATED BY DEFAULT AS IDENTITY"));assert!(sql.contains("PRIMARY KEY (\"id\")"));
    assert!(n::create_table_sql(&json!({"name":"fixture","columns":[{"name":"x","typeName":"TEXT); DROP TABLE x;--"}]}),false).is_err());
    assert!(n::create_table_sql(&json!({"name":"fixture","columns":[{"name":"x","typeName":"TEXT","defaultValue":"'x'); DROP TABLE y;--"}]}),false).is_err());
    assert!(n::create_table_sql(&json!({"name":"fixture","columns":[{"name":"x","typeName":"INTEGER","primaryKeyOrdinal":2}]}),false).is_err());
}
#[test]
fn import_plan_validates_columns_required_fields_values_and_source_namespace(){
    let description=json!({"columns":[{"name":"Id","nullable":false,"requiredOnInsert":true},{"name":"body","nullable":true},{"name":"calc","generated":"stored"},{"name":"identity","identityGeneration":"always"}]});
    let batch=json!({"batchIndex":0,"columns":["id","body"],"rows":[{"rowNumber":1,"values":[{"kind":"number","value":1},{"kind":"text","text":"fixture"}]}]});
    let plan=n::import_plan(&batch,&description).unwrap();assert_eq!(plan.columns,vec!["Id","body"]);assert_eq!(plan.rows[0].1,vec![json!(1),json!("fixture")]);
    let mut invalid=batch.clone();invalid["columns"]=json!(["Id","Id"]);assert!(n::import_plan(&invalid,&description).is_err());
    invalid=batch.clone();invalid["columns"]=json!(["body","calc"]);assert!(n::import_plan(&invalid,&description).is_err());
    invalid=batch.clone();invalid["columns"]=json!(["Id","identity"]);assert!(n::import_plan(&invalid,&description).is_err());
    invalid=batch.clone();invalid["rows"][0]["values"][0]=json!({"kind":"null"});assert!(n::import_plan(&invalid,&description).is_err());
    invalid=batch.clone();invalid["rows"][0]["values"][1]=json!({"kind":"text","text":"preview","truncated":true});assert!(n::import_plan(&invalid,&description).is_err());
    invalid=batch.clone();invalid["rows"]=json!([]);assert!(n::import_plan(&invalid,&description).is_err());
    let source=n::transfer_source("view:other\\.schema.test",false).unwrap();assert_eq!(source["target"]["schema"],"other.schema");assert_eq!(source["target"]["table"],"test");assert_eq!(source["target"]["kind"],"view");
}
